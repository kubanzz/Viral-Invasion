import { build } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
await mkdir('dist', { recursive: true });
const result = await build({ entryPoints: ['src/main.ts'], bundle: true, format: 'iife', target: ['chrome110', 'edge110'], outfile: 'dist/game.js', minify: true, metafile: true, legalComments: 'none' });
const css = await readFile('src/style.css', 'utf8');
const { version } = JSON.parse(await readFile('package.json', 'utf8'));
const html = (await readFile('index.html', 'utf8')).replace('<!-- STYLES -->', `<style>${css}</style>`).replace('<script type="module" src="/src/main.ts"></script>', '<script src="./game.js"></script>');
await writeFile('dist/index.html', html);
await writeFile('dist/build-meta.json', JSON.stringify({ game: 'viral-invasion', version, stage: 'G0', format: 'iife', ...result.metafile }, null, 2));
console.log('Offline release ready: dist/index.html + game.js (classic IIFE, all assets local).');
